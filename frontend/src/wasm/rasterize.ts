export function rasterToPngBlobUrl(data: Float32Array, m: number, n: number): Promise<string> {
  let min = Infinity;
  let max = -Infinity;
  for (let i = 0; i < data.length; i++) {
    const v = data[i];
    if (Number.isFinite(v)) {
      if (v < min) min = v;
      if (v > max) max = v;
    }
  }

  const range = max - min || 1;
  const canvas = document.createElement('canvas');
  canvas.width = n;
  canvas.height = m;
  const ctx = canvas.getContext('2d');
  if (!ctx) return Promise.resolve('');
  const imgData = ctx.createImageData(n, m);

  for (let i = 0; i < data.length; i++) {
    const v = data[i];
    const px = i * 4;
    if (Number.isFinite(v)) {
      const idx = Math.min(255, Math.max(0, Math.floor(((v - min) / range) * 255))) * 3;
      imgData.data[px] = MAGMA[idx];
      imgData.data[px + 1] = MAGMA[idx + 1];
      imgData.data[px + 2] = MAGMA[idx + 2];
      imgData.data[px + 3] = 255;
    } else {
      imgData.data[px + 3] = 0;
    }
  }
  ctx.putImageData(imgData, 0, 0);

  return new Promise((resolve, reject) => {
    canvas.toBlob((b) => {
      if (b) resolve(URL.createObjectURL(b));
      else reject(new Error('Failed to create blob'));
    }, 'image/png');
  });
}
